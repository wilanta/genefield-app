import { useTranslation } from "@/components/language-provider";
import { tourEvents } from "@/onboarding/tourEvents";
import { useState } from "react";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import type { BreedDesignerCandidate } from "@/pages/BreedDesigner/types";
import { candidateStore } from "@/services";
import { CandidateNameConflictError } from "@/types/research";

interface Props {
  candidates: BreedDesignerCandidate[];
  onOpenInCrossLab: (parentA: string, parentB: string) => void;
  onGoToWorkspace: () => void;
}

type SaveState = "idle" | "saving" | "saved" | "conflict";

/**
 * Save routes the candidate through the shared CandidateStore (real SQLite in
 * the desktop app, in-session memory in preview). "Add" performs the same save
 * but is labeled as a quick-add. Conflict errors surface a message; the row
 * state reflects the last attempt.
 */
export function CandidateTable({
  candidates,
  onOpenInCrossLab,
  onGoToWorkspace,
}: Props) {
  const { t: tr } = useTranslation();
  const [state, setState] = useState<Map<string, SaveState>>(new Map());
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const get = (id: string): SaveState => state.get(id) ?? "idle";

  const save = async (c: BreedDesignerCandidate, kind: "save" | "add") => {
    setState((prev) => {
      const next = new Map(prev);
      next.set(c.candidateId, "saving");
      return next;
    });
    setErrorMsg(null);
    const baseName =
      kind === "add"
        ? `${c.parentA} × ${c.parentB} (${c.candidateId})`
        : `${c.parentA} × ${c.parentB}`;
    const name = tourEvents.candidateName(baseName, tr("Guided Tour"));
    try {
      const saved = await candidateStore.create({
        name,
        parentA: c.parentA,
        parentB: c.parentB,
        notes: `Generated by Breed Designer · candidate ${c.candidateId}. Genotype: ${c.genotype}. Historical: ${c.historical}.`,
        source: "breed-designer",
        analysis: c.analysis,
        reviewStatus: "draft",
        tags: [kind],
      });
      tourEvents.emit("candidate-saved", {
        id: saved.id,
        parents: [c.parentA, c.parentB],
      });
      setState((prev) => {
        const next = new Map(prev);
        next.set(c.candidateId, "saved");
        return next;
      });
    } catch (e) {
      if (e instanceof CandidateNameConflictError) {
        setState((prev) => {
          const next = new Map(prev);
          next.set(c.candidateId, "conflict");
          return next;
        });
        setErrorMsg(tr('A candidate named "{name}" already exists.', { name }));
      } else {
        setState((prev) => {
          const next = new Map(prev);
          next.set(c.candidateId, "idle");
          return next;
        });
        setErrorMsg(tr("Could not save candidate. ") + (e as Error).message);
      }
    }
  };

  return (
    <div className="breed-designer-candidates">
      <p className="px-3 py-2 text-xs text-muted-foreground">
        {tr(
          "Relative application score used to prioritize candidate pairs; not a probability of breeding success.",
        )}
      </p>
      <div className="breed-designer-candidate-scroll">
        <Table>
          <colgroup>
            <col style={{ width: "20%" }} />
            <col style={{ width: "10.5%" }} />
            <col style={{ width: "10.5%" }} />
            <col style={{ width: "9%" }} />
            <col style={{ width: "13%" }} />
            <col style={{ width: "13%" }} />
            <col style={{ width: "24%" }} />
          </colgroup>
          <TableHeader>
            <TableRow className="border-b hover:bg-transparent">
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Candidate")}
                <br />
                ID
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Parent A")}
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Parent B")}
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Genotype")}
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Historical")}
                <br />
                {tr("cross")}
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Expert review")}
                <br />
                {tr("status")}
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                {tr("Actions")}
              </TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {candidates.map((c) => {
              const s = get(c.candidateId);
              const justSaved = s === "saved";
              const conflicted = s === "conflict";
              return (
                <TableRow key={c.candidateId} className="border-b">
                  <TableCell className="px-3 text-sm font-mono">
                    {c.candidateId}
                    {c.analysis && (
                      <div className="mt-1 whitespace-normal text-[10px] text-muted-foreground [overflow-wrap:anywhere]">
                        {tr("Prioritization Score:")}{" "}
                        {c.analysis.applicationScore?.toFixed(4)}
                        <br />
                        {Object.entries(c.analysis.predictions).map(
                          ([t, p]) => (
                            <div key={t}>
                              {t}: {p.value.toFixed(2)} {tr(p.units)}
                            </div>
                          ),
                        )}
                      </div>
                    )}
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className="font-mono">{c.parentA}</span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className="font-mono">{c.parentB}</span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span
                      className={
                        "inline-flex items-center gap-1.5 text-[13px] " +
                        (c.genotype === "Both"
                          ? "text-foreground"
                          : "text-muted-foreground")
                      }
                    >
                      <span
                        className={
                          "size-[7px] shrink-0 rounded-full " +
                          (c.genotype === "Both"
                            ? "bg-primary"
                            : "border border-muted-foreground bg-transparent")
                        }
                      />
                      {tr(c.genotype)}
                    </span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span
                      className={
                        "rounded-full bg-muted px-2 py-0.5 text-[11px] " +
                        (c.historicalRecorded
                          ? "text-foreground"
                          : "text-muted-foreground")
                      }
                    >
                      {tr(c.historical)}
                    </span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className="rounded-full bg-muted px-2 py-0.5 text-[11px] text-muted-foreground">
                      {tr(c.researchStatus)}
                    </span>
                  </TableCell>
                  <TableCell className="breed-designer-actions px-3">
                    <div>
                      <button
                        type="button"
                        className="text-primary"
                        onClick={() => onOpenInCrossLab(c.parentA, c.parentB)}
                      >
                        {tr("Open in Cross Lab")}
                      </button>
                      <span aria-hidden> · </span>
                      <button
                        type="button"
                        data-tour="breed-save"
                        className={
                          conflicted ? "text-destructive" : "text-primary"
                        }
                        disabled={s === "saving"}
                        onClick={() => save(c, "save")}
                      >
                        {s === "saving"
                          ? tr("Saving…")
                          : justSaved
                            ? tr("Saved")
                            : conflicted
                              ? tr("Conflict")
                              : tr("Save")}
                      </button>
                      <span aria-hidden> · </span>
                      <button
                        type="button"
                        className={
                          conflicted ? "text-destructive" : "text-primary"
                        }
                        disabled={s === "saving"}
                        onClick={() => save(c, "add")}
                      >
                        {tr("Add")}
                      </button>
                    </div>
                  </TableCell>
                </TableRow>
              );
            })}
            {candidates.length === 0 ? (
              <TableRow className="hover:bg-transparent">
                <TableCell
                  colSpan={7}
                  className="px-3 py-10 text-center text-sm text-muted-foreground"
                >
                  {tr(
                    "No candidate pairs match the current pool and generation rules.",
                  )}
                </TableCell>
              </TableRow>
            ) : null}
          </TableBody>
        </Table>
      </div>
      {state.size > 0 && (
        <div className="border-t border-border px-4 py-2.5" aria-live="polite">
          {errorMsg ? (
            <p className="text-xs text-destructive">{tr(errorMsg)}</p>
          ) : (
            <p className="text-xs text-muted-foreground">
              {tr("Saved candidates go to your")}{" "}
              <button
                type="button"
                onClick={onGoToWorkspace}
                className="mx-0.5 font-medium text-primary hover:underline"
              >
                {tr("Candidate Workspace")}
              </button>
              .
            </p>
          )}
        </div>
      )}
    </div>
  );
}
