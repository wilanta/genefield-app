import { useState } from "react";
import {
  ExternalLink,
  BookmarkPlus,
  Plus,
  FolderKanban,
  Check,
} from "lucide-react";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import type { BreedDesignerCandidate } from "@/pages/BreedDesigner/types";
import { candidateStore } from "@/services";
import { CandidateNameConflictError } from "@/types/research";

interface Props {
  candidates: BreedDesignerCandidate[];
  onOpenInCrossLab: (parentA: string, parentB: string) => void;
  onGoToWorkspace: () => void;
}

type SaveState = "idle" | "saving" | "saved" | "conflict";

/**
 * Save routes the candidate through the shared CandidateStore (real SQLite in
 * the desktop app, in-session memory in preview). "Add" performs the same save
 * but is labeled as a quick-add. Conflict errors surface a message; the row
 * state reflects the last attempt.
 */
export function CandidateTable({
  candidates,
  onOpenInCrossLab,
  onGoToWorkspace,
}: Props) {
  const [state, setState] = useState<Map<string, SaveState>>(new Map());
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const get = (id: string): SaveState => state.get(id) ?? "idle";

  const save = async (c: BreedDesignerCandidate, kind: "save" | "add") => {
    setState((prev) => {
      const next = new Map(prev);
      next.set(c.candidateId, "saving");
      return next;
    });
    setErrorMsg(null);
    const name =
      kind === "add"
        ? `${c.parentA} × ${c.parentB} (${c.candidateId})`
        : `${c.parentA} × ${c.parentB}`;
    try {
      await candidateStore.create({
        name,
        parentA: c.parentA,
        parentB: c.parentB,
        notes: `Generated by Breed Designer · candidate ${c.candidateId}. Genotype: ${c.genotype}. Historical: ${c.historical}.`,
        source: "breed-designer",
        reviewStatus: "draft",
        tags: [kind],
      });
      setState((prev) => {
        const next = new Map(prev);
        next.set(c.candidateId, "saved");
        return next;
      });
    } catch (e) {
      if (e instanceof CandidateNameConflictError) {
        setState((prev) => {
          const next = new Map(prev);
          next.set(c.candidateId, "conflict");
          return next;
        });
        setErrorMsg(e.message);
      } else {
        setState((prev) => {
          const next = new Map(prev);
          next.set(c.candidateId, "idle");
          return next;
        });
        setErrorMsg("Could not save candidate. " + (e as Error).message);
      }
    }
  };

  return (
    <div className="rounded-xl border border-border bg-card shadow-[var(--gf-card-shadow)]">
      <div className="flex flex-col overflow-hidden">
        <Table>
          <TableHeader>
            <TableRow className="border-b hover:bg-transparent">
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Candidate
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Parent A
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Parent B
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Genotype
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Historical cross
              </TableHead>
              <TableHead className="px-3 py-2 text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Research status
              </TableHead>
              <TableHead className="px-3 py-2 text-right text-[11px] font-medium uppercase tracking-wider text-muted-foreground">
                Actions
              </TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {candidates.map((c) => {
              const s = get(c.candidateId);
              const justSaved = s === "saved";
              const conflicted = s === "conflict";
              return (
                <TableRow key={c.candidateId} className="h-[42px] border-b">
                  <TableCell className="px-3 text-sm font-mono">
                    {c.candidateId}
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className="font-mono">{c.parentA}</span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className="font-mono">{c.parentB}</span>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <Badge
                      variant={c.genotype === "Both" ? "secondary" : "outline"}
                      className="text-[11px] font-medium"
                    >
                      {c.genotype}
                    </Badge>
                  </TableCell>
                  <TableCell className="px-3 text-sm">
                    <span className={c.historicalRecorded ? "text-foreground" : "text-muted-foreground"}>
                      {c.historical}
                    </span>
                  </TableCell>
                  <TableCell className="px-3 text-sm text-muted-foreground">
                    {c.researchStatus}
                  </TableCell>
                  <TableCell className="px-3">
                    <div className="flex items-center justify-end gap-1.5">
                      <Button
                        variant="outline"
                        size="sm"
                        className="h-7 gap-1.5 px-2 text-xs"
                        onClick={() => onOpenInCrossLab(c.parentA, c.parentB)}
                      >
                        <ExternalLink className="size-3.5" />
                        Open in Cross Lab
                      </Button>
                      <Button
                        variant="ghost"
                        size="sm"
                        className={
                          "h-7 gap-1.5 px-2 text-xs" +
                          (justSaved
                            ? " text-primary"
                            : conflicted
                              ? " text-destructive"
                              : "")
                        }
                        disabled={s === "saving"}
                        onClick={() => save(c, "save")}
                      >
                        {justSaved ? (
                          <Check className="size-3.5" />
                        ) : (
                          <BookmarkPlus className="size-3.5" />
                        )}
                        {s === "saving"
                          ? "Saving…"
                          : justSaved
                            ? "Saved"
                            : conflicted
                              ? "Conflict"
                              : "Save"}
                      </Button>
                      <Button
                        variant="ghost"
                        size="sm"
                        className={
                          "h-7 gap-1.5 px-2 text-xs" +
                          (conflicted ? " text-destructive" : "")
                        }
                        disabled={s === "saving"}
                        onClick={() => save(c, "add")}
                      >
                        <Plus className="size-3.5" />
                        Add
                      </Button>
                    </div>
                  </TableCell>
                </TableRow>
              );
            })}
            {candidates.length === 0 ? (
              <TableRow className="hover:bg-transparent">
                <TableCell
                  colSpan={7}
                  className="px-3 py-10 text-center text-sm text-muted-foreground"
                >
                  No candidate pairs match the current pool and generation rules.
                </TableCell>
              </TableRow>
            ) : null}
          </TableBody>
        </Table>
      </div>
      <div className="border-t border-border px-4 py-2.5">
        {errorMsg ? (
          <p className="text-xs text-destructive">{errorMsg}</p>
        ) : (
          <p className="flex items-center gap-1.5 text-xs text-muted-foreground">
            <FolderKanban className="size-3.5" />
            <span>
              Saved candidates go to your Candidate
              <button
                type="button"
                onClick={onGoToWorkspace}
                className="mx-0.5 font-medium text-primary hover:underline"
              >
                Workspace
              </button>
              . In preview mode they stay in-session only.
            </span>
          </p>
        )}
      </div>
    </div>
  );
}
